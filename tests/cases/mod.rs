/// Cases whose libc result is not the standard's. Each has a direct
/// assertion in `tests/engine.rs`.
pub const LIBC_DIFFERS: &[(&[u8], &str)] = &[
    // glibc returns EOF; a suppressed conversion completed, so 0.
    (b"1", "%*d%d"),
    // glibc assigns 100; `100e` is an incomplete item.
    (b"100er", "%f"),
    // glibc assigns 0 and leaves `xg` or `g`; `0x` is an incomplete item.
    (b"0xg", "%x"),
    (b"0xg", "%i"),
];
